// Generates tft/COMPONENTS.md from design/layout.ts. Usage: bun design/components.ts
import { COLORS, FONT_SPECS, FontName, PAGES, PICTURES } from './layout';

export function rgb565(hex: string): number {
  const n = parseInt(hex.slice(1), 16);
  const r = (n >> 16) & 0xff;
  const g = (n >> 8) & 0xff;
  const b = n & 0xff;
  return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
}

const XCEN = { left: 0, center: 1, right: 2 } as const;
const YCEN = { top: 0, center: 1, bottom: 2 } as const;

export function componentsMarkdown(): string {
  const out: string[] = [];
  out.push('# TFT component map (generated — do not edit)');
  out.push('');
  out.push('Generated by `bun design/components.ts` from `design/layout.ts`. The firmware, the app and `tft/BUILD.md` use these names.');
  out.push('');
  out.push('## Pictures (import in this order)');
  out.push('');
  out.push('| # | File | Symbol in Program.s |');
  out.push('|---|---|---|');
  PICTURES.forEach((p, i) => out.push(`| ${i + 1} | \`tft/assets/${p}.png\` | \`p_${p.replace('-', '_')}\` |`));
  out.push('');
  out.push('## Fonts');
  out.push('');
  out.push('| Symbol | Font | Size | Characters | Use |');
  out.push('|---|---|---|---|---|');
  (Object.keys(FONT_SPECS) as FontName[]).forEach((f) => {
    const s = FONT_SPECS[f];
    out.push(`| ${f} | ${s.family} | ${s.px} | ${s.chars} | ${s.note} |`);
  });
  out.push('');
  out.push('## Colours (pco)');
  out.push('');
  out.push('| Name | Hex | pco |');
  out.push('|---|---|---|');
  (Object.keys(COLORS) as Array<keyof typeof COLORS>).forEach((c) => out.push(`| ${c} | ${COLORS[c]} | ${rgb565(COLORS[c])} |`));

  for (const page of PAGES) {
    out.push('');
    out.push(`## Page ${page.id}: \`${page.name}\``);
    out.push('');
    if (page.name === 'boot') {
      out.push('Kept from Blackymas. Only set the page background: `sta` = image, `pic` = `p_boot`.');
      continue;
    }
    out.push(`Page: \`sta\` = image, \`pic\` = \`p_${page.name}\`.`);
    out.push('');
    if (page.components.length) {
      out.push('| Name | Type | x | y | w | h | font | pco | xcen | ycen | isbr | crop (picc) | touch | sample |');
      out.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
      for (const c of page.components) {
        const picc = c.crop === 'on' ? `p_${page.name}_on` : `p_${page.name}`;
        out.push(`| ${c.name} | Text | ${c.x} | ${c.y} | ${c.w} | ${c.h} | ${c.font} | ${rgb565(COLORS[c.color])} | ${XCEN[c.align]} | ${YCEN[c.valign ?? 'center']} | ${c.wrap ? 1 : 0} | ${picc} | ${c.touch ?? ''} | ${c.sample} |`);
      }
    }
    if (page.hotspots.length) {
      out.push('');
      out.push('| Hotspot | x | y | w | h | touch |');
      out.push('|---|---|---|---|---|---|');
      for (const h of page.hotspots) out.push(`| ${h.name} | ${h.x} | ${h.y} | ${h.w} | ${h.h} | ${h.touch} |`);
    }
  }
  out.push('');
  return out.join('\n');
}

if (import.meta.main) {
  await Bun.write('tft/COMPONENTS.md', componentsMarkdown());
  console.log('wrote tft/COMPONENTS.md');
}
