// Generates tft/ROUND2.md: the Editor edits that take the TFT currently on the panel (first Soft dark build,
// snapshot in design/built-r1.json) to the round-2 layout. Usage: bun design/round2.ts
import builtR1 from './built-r1.json';
import { PAGES, PICTURES } from './layout';

type Box = { name: string; x: number; y: number; w: number; h: number; font?: string };
const BUILT = builtR1 as Record<string, { components: Box[]; hotspots: Box[] }>;
const FIRST_NEW_PICTURE_ID = 56; // the first Soft dark build has pictures 48-55
const NEW_PICTURES = PICTURES.slice(8);

const SEND_CSV = ['printh 92', 'prints "localevent",0', 'printh 00', 'prints csv.txt,0', 'printh 00', 'printh FF FF FF'];
const csvScript = (csv: string): string[] => [`csv.txt="${csv}"`, ...SEND_CSV];

// Touch Release Event scripts for everything new in round 2.
const SCRIPTS: Record<string, string[]> = {
  NAV_MEDIA: ['page media'],
  NAV_TIMER: ['page timer'],
  MEDIA_TOGGLE: csvScript('media,toggle,'),
  MEDIA_PREV: csvScript('media,prev,'),
  MEDIA_NEXT: csvScript('media,next,'),
  MEDIA_VOL_DOWN: csvScript('media,vol,-1'),
  MEDIA_VOL_UP: csvScript('media,vol,1'),
  MEDIA_PLAYER: csvScript('media,player,next'),
  TIMER_ADD_60: csvScript('timer,add,60'),
  TIMER_ADD_300: csvScript('timer,add,300'),
  TIMER_ADD_600: csvScript('timer,add,600'),
  TIMER_ACT: csvScript('timer,act,'),
  TIMER_RESET: csvScript('timer,reset,'),
};

function diffRows(kind: 'Text' | 'Hotspot', now: Box[], before: Box[]): string[] {
  const rows: string[] = [];
  for (const c of now) {
    const o = before.find((b) => b.name === c.name);
    if (!o) {
      rows.push(`| ${c.name} | ${kind} | **add** (see COMPONENTS.md) |`);
      continue;
    }
    const changes: string[] = [];
    for (const k of ['x', 'y', 'w', 'h'] as const) if (o[k] !== c[k]) changes.push(`${k} ${o[k]} → **${c[k]}**`);
    if (kind === 'Text' && o.font !== c.font) changes.push(`font → **${c.font}**`);
    if (changes.length) rows.push(`| ${c.name} | ${kind} | ${changes.join(', ')} |`);
  }
  for (const o of before) if (!now.some((c) => c.name === o.name)) rows.push(`| ${o.name} | ${kind} | **delete** |`);
  return rows;
}

export function round2Markdown(): string {
  const newIds = NEW_PICTURES.map((p, i) => `p_${p.replace('-', '_')}=${FIRST_NEW_PICTURE_ID + i}`).join(',');
  const out: string[] = [
    '# Round 2: safe area, graphite, Homey icons, media and timer (generated — do not edit)', '',
    'Generated by `bun design/round2.ts`, compared with the TFT currently on the panel (`design/built-r1.json`).',
    'Work in a copy: Save As `~/nspanel-tft/nspanel_soft_dark_r2.HMI`.', '',
    '## Steps', '',
    '1. **Icon font:** copy `tft/fonts/NSPanelHomeyGlyphs.ttf` into the bottle\'s `C:\\windows\\Fonts`, delete `NSPanelHomeyIcons.ttf` there, restart Nextion Editor.',
    '   The icons sit at U+4E00–U+5496 (CJK range): the font generator turns private-use characters into empty code-0 glyphs.',
    '   New family name (*NSPanel Homey Glyphs*) because Wine cached the old font and substituted a Chinese system font.',
    '2. **Generate two fonts** (Tools → Font Generator): font *NSPanel Homey Glyphs*, encoding **utf-8**, anti-aliasing on,',
    '   characters: **Specify**, either load `tft/fonts/homey-icons-chars-utf16.txt` (UTF-16 LE, like the round-1 charsets)',
    '   or paste `tft/fonts/homey-icons-chars.txt` (`pbcopy < tft/fonts/homey-icons-chars.txt`).',
    '   Test first with only the first 5 characters: the preview must show icons, not blanks or Chinese characters.',
    '   - height **24** → `homey24` (`F_HICON_S`)',
    '   - height **32** → `homey32` (`F_HICON_L`)',
    '3. **Replace the 8 existing pictures** (ids 48–55) with the files of the same name from `tft/assets/` (Picture panel → Replace).',
    '   Under CrossOver the link in the "Add Picture" window opens a Windows file dialog that can appear *behind* the Editor',
    '   (the Editor then looks frozen). Find it via the CrossOver/Wine window list or Cmd-Tab, and paste the path into',
    '   "File name", e.g. `Z:\\Users\\timbroddin\\nspanel-tft\\r2-assets\\home.png`. Dragging from Finder does not work.',
    `4. **Add ${NEW_PICTURES.length} pictures** in this order: ${NEW_PICTURES.map((p) => `\`${p}.png\``).join(', ')} (ids ${FIRST_NEW_PICTURE_ID}–${FIRST_NEW_PICTURE_ID + NEW_PICTURES.length - 1}).`,
    `   In **Program.s**, add after the existing \`int p_boot=…\` line: \`int ${newIds}\``,
    '5. **Edit the existing pages** as listed below.',
    '6. **Add two pages at the end**, named exactly `media` (id 7) and `timer` (id 8). Page `sta` = image, `pic` = `p_media` / `p_timer`.',
    '   Build them from **COMPONENTS.md** (Page 7 `media`, Page 8 `timer`), the same way as the other pages:',
    '   Preinitialize Event `dim=brightness` + `sendme`, a `tm_back` timer (60000 ms → `page home`), a TouchCap `tc` that restarts it,',
    '   hotspot `go_home` → `page home`, and a string Variable `csv` (maxl 40).',
    '   Progress Bars (`prog`, `vol`): `sta` = solid colour, `pco` and `bco` from COMPONENTS.md, `val` 0.',
    '7. **Touch scripts** (Touch Release Event) for the new components and hotspots: see the end of this file.',
    '8. Compile (0 errors), File → TFT file output → `~/nspanel-tft/nspanel_soft_dark_r2.tft`.',
    '9. Send Claude a screenshot of the **Fonts** panel and the **Pictures** panel (ids and names).', '',
  ];
  for (const page of PAGES) {
    const before = BUILT[page.name];
    if (!before) continue; // new page: built from COMPONENTS.md
    const rows = [...diffRows('Text', page.components, before.components), ...diffRows('Hotspot', page.hotspots, before.hotspots)];
    if (!rows.length) continue;
    out.push(`## Page ${page.id} \`${page.name}\``, '', '| Component | Type | Change |', '|---|---|---|', ...rows, '');
  }
  for (const page of PAGES.filter((p) => !BUILT[p.name])) {
    out.push(`## Page ${page.id} \`${page.name}\` (new)`, '', `Build every component and hotspot from COMPONENTS.md → "Page ${page.id}: \`${page.name}\`".`, '');
  }
  out.push('## Touch scripts', '');
  for (const [name, lines] of Object.entries(SCRIPTS)) out.push(`### ${name}`, '```', ...lines, '```', '');
  return out.join('\n');
}

if (import.meta.main) {
  await Bun.write('tft/ROUND2.md', round2Markdown());
  console.log('wrote tft/ROUND2.md');
}
